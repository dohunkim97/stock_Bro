// 줄글(story, master_analyst_final_verdict, analyst_financial_summary) 속을
// 스캔할 때는 "정상/보통/주의/안전"처럼 짧고 흔한 단어는 뺀다 — "비정상",
// "안전벨트"처럼 전혀 다른 뜻의 단어 중간에 우연히 끼어 있을 수 있어서다.
// 배지 자체를 통째로 감쌀 때(findGlossaryMatch, 정확히 일치)는 이 단어들도
// 그대로 쓴다 — 배지 값 자체가 이미 "정상"/"안전" 그 자체이므로 오매칭
// 걱정이 없다.
const NARRATIVE_SCAN_EXCLUDE = new Set(["정상", "보통", "주의", "안전"]);

export type GlossaryHit = { term: string; explanation: string };

// 배지 텍스트 전체가 사전 항목과 정확히 일치하는지 확인한다(부분 일치가
// 아니라 정확히 일치 — 배지는 항상 값 하나를 통째로 담고 있어서 이렇게
// 해야 "안전"처럼 흔한 단어도 안전하게 매칭할 수 있다).
export function findGlossaryMatch(text: string): GlossaryHit | null {
  const trimmed = text.trim();
  const explanation = FINANCE_GLOSSARY[trimmed];
  return explanation ? { term: trimmed, explanation } : null;
}

export type TextSegment = { text: string; glossary?: GlossaryHit };

// story처럼 긴 줄글 속에 섞인 용어(예: "이자보상배율이 11배를 상회하여...")
// 를 찾아서 그 부분만 따로 떼어낸다 — 나머지는 그냥 일반 텍스트 조각.
// 렌더링 쪽(GlossaryText)이 각 조각을 순회하며 glossary가 있는 조각만
// 클릭/호버 가능한 용어로 감싼다. 긴 키(예: "고환율 수혜(수출주)")를 짧은
// 키("고환율 수혜")보다 먼저 검사해서 더 구체적인 쪽이 이기게 한다.
export function splitByGlossaryTerms(text: string): TextSegment[] {
  const keys = Object.keys(FINANCE_GLOSSARY)
    .filter((k) => !NARRATIVE_SCAN_EXCLUDE.has(k))
    .sort((a, b) => b.length - a.length);
  if (keys.length === 0 || !text) return [{ text }];

  const segments: TextSegment[] = [];
  let i = 0;
  while (i < text.length) {
    const hitKey = keys.find((key) => text.startsWith(key, i));
    if (hitKey) {
      segments.push({ text: hitKey, glossary: { term: hitKey, explanation: FINANCE_GLOSSARY[hitKey] } });
      i += hitKey.length;
      continue;
    }
    let next = text.length;
    for (let j = i + 1; j < text.length; j++) {
      if (keys.some((key) => text.startsWith(key, j))) {
        next = j;
        break;
      }
    }
    segments.push({ text: text.slice(i, next) });
    i = next;
  }
  return segments;
}
